-- 0021_written_practices.sql
-- The written libraries — journal prompts, movement sequences, recipes — move
-- out of Swift and into tables, so the team can add, edit or retire one in the
-- dashboard without a release. Until now they were `JournalPrompt.all`,
-- `Exercise.all` and `Recipe.all` in Models.swift: every new prompt, every
-- typo fix, was an App Review.
--
--   1. `journal_prompts`, `exercises`, `recipes` — catalog tables, readable by
--      both client roles (published rows only), written by the team only.
--   2. A shape check on a movement sequence's steps, so a malformed sequence is
--      refused in the dashboard rather than silently hidden in the app.
--   3. The content that was in Swift, seeded under THE SAME IDS.
--
-- ⚠️ THE IDS ARE A CONTRACT. Four things point at a written practice by
-- (content_kind, content_id), none of them with a foreign key:
--   * `practice_plays` — the ledger, which is never rewritten;
--   * `practice_credits` (0020) — which guide it is credited to;
--   * `programs.curriculum` — Finding Ground (0014) references all 13;
--   * the phone — a member's journal reflection is saved under `journal.<id>`.
-- So an id is never changed and never reused. To take a practice down, set
-- `published = false`: it leaves the lists, and a program day that points at
-- it quietly shrinks to what remains (ProgramStore drops what it can't find).
-- Deleting the row does the same, but frees nothing and loses the text.
--
-- `practice_credits` stays as it is. It exists (0020) because these libraries
-- had no row to carry an `instructor_id`; now they do, and folding the credit
-- into each row — as sessions and programs have it — is a reasonable next
-- step. It is left for a change of its own: the live credits, the
-- `-preview-instructors` fixture and the runbook all read the table today.
--
-- The written libraries still take no part in payouts (`creditsCreator` in
-- Swift). A recipe's `angle` is a dietary angle ("Anti-inflammatory"), never a
-- person — which is why it is not called `lead`, the column that names the
-- paid guide on a session.
--
-- APPLIED 2026-09-29 through the Management API and recorded in
-- supabase_migrations.schema_migrations (0021), after a dry run inside a
-- rolled-back transaction. Verified live: 5 / 5 / 3 rows; every written
-- activity in every curriculum and every practice credit resolves; the next
-- dashboard insert gets id 6 / 6 / 4; the steps check refuses a nameless,
-- blank, non-object, numeric or empty sequence; both client roles hold SELECT
-- and nothing else; as `anon` and as an anonymous guest the tables read 200,
-- a POST / PATCH answers 42501 and the check function is not callable as an
-- RPC (42501); an unpublished row is invisible. The test guests were deleted.

