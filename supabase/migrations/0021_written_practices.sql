create table if not exists public.journal_prompts (
    id          bigint      generated by default as identity primary key,
    -- The question itself — the row title and the page heading.
    title       text        not null check (btrim(title) <> ''),
    -- The longer framing under it.
    prompt      text        not null check (btrim(prompt) <> ''),
    -- The eyebrow: "Self-compassion", "Letting go".
    theme       text        not null default '',
    -- `bucket/path.jpg`, like every catalog image. Null draws a quiet gradient.
    image_url   text,
    published   boolean     not null default true,
    sort_order  integer,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

-- A sequence's steps, in order: [{"name": "Cat–Cow", "detail": "8 slow reps"}].
-- `name` is required and non-blank; `detail` is optional. At least one step.
--
-- A function because a CHECK can't hold a subquery, and a CASE because SQL
-- doesn't promise to short-circuit AND — `jsonb_array_length` on a non-array
-- raises, which would answer a bad edit with a confusing error instead of the
-- constraint's name.
create or replace function public.is_valid_exercise_steps(steps jsonb)
returns boolean
language sql
immutable
set search_path = ''
as $$
    select case
        when steps is null or jsonb_typeof(steps) <> 'array' then false
        when jsonb_array_length(steps) = 0 then false
        else not exists (
            select 1
            from jsonb_array_elements(steps) as s(step)
            where jsonb_typeof(s.step) <> 'object'
               or jsonb_typeof(s.step -> 'name') is distinct from 'string'
               or btrim(s.step ->> 'name') = ''
               or coalesce(jsonb_typeof(s.step -> 'detail'), 'null') not in ('string', 'null')
        )
    end
$$;

-- Only the constraint calls it. Supabase grants EXECUTE on new functions to
-- the client roles, which would also publish it as an RPC.
revoke execute on function public.is_valid_exercise_steps(jsonb) from public, anon, authenticated;

create table if not exists public.exercises (
    id                bigint      generated by default as identity primary key,
    title             text        not null check (btrim(title) <> ''),
    -- "Mobility", "Core", "Yoga" — yoga lives here, not in a track of its own.
    focus             text        not null default '',
    -- Also the bound the ledger clamps a sitting's seconds against.
    duration_seconds  integer     not null check (duration_seconds > 0),
    image_url         text,
    blurb             text        not null default '',
    steps             jsonb       not null
                                  constraint exercises_steps_shape
                                  check (public.is_valid_exercise_steps(steps)),
    published         boolean     not null default true,
    sort_order        integer,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now()
);

create table if not exists public.recipes (
    id           bigint      generated by default as identity primary key,
    title        text        not null check (btrim(title) <> ''),
    -- A dietary angle ("Gut-friendly"), shown as the eyebrow. Not a person.
    angle        text        not null default '',
    minutes      integer     not null check (minutes > 0),
    servings     integer     not null check (servings > 0),
    image_url    text,
    blurb        text        not null default '',
    -- One line each, in order. At least one, and no nulls — `array_position`
    -- finds a null where `= any` can't.
    ingredients  text[]      not null
                             check (cardinality(ingredients) > 0 and array_position(ingredients, null) is null),
    steps        text[]      not null
                             check (cardinality(steps) > 0 and array_position(steps, null) is null),
    published    boolean     not null default true,
    sort_order   integer,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now()
);

