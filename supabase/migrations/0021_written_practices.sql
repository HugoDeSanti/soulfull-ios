-- ---------------------------------------------------------------------------
-- 2. Access: catalog, read-only, published rows
-- ---------------------------------------------------------------------------
--
-- Both client roles (the 0003 trap: an anonymous guest is `authenticated`).
-- No write policy at all — the team writes in the dashboard. And the grants
-- are narrowed as well as the policies, because Supabase's default privileges
-- hand ALL on a new table to both roles (the 0015 lesson).

alter table public.journal_prompts enable row level security;
alter table public.exercises       enable row level security;
alter table public.recipes         enable row level security;

drop policy if exists "Published journal prompts are public" on public.journal_prompts;
create policy "Published journal prompts are public"
    on public.journal_prompts for select to anon, authenticated using (published);

drop policy if exists "Published exercises are public" on public.exercises;
create policy "Published exercises are public"
    on public.exercises for select to anon, authenticated using (published);

drop policy if exists "Published recipes are public" on public.recipes;
create policy "Published recipes are public"
    on public.recipes for select to anon, authenticated using (published);

revoke all on public.journal_prompts, public.exercises, public.recipes from anon, authenticated, public;
grant select on public.journal_prompts, public.exercises, public.recipes to anon, authenticated;

