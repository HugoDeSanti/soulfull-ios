#!/usr/bin/env bash
#
# Assembles the standalone legal pages from _shared.css + src/*.body.html.
#
# The generated *.html files are self-contained: one <style> block, no external
# assets beyond the Geist webfont, and every rule scoped under `.sg-legal` so
# the page can be pasted whole into a Squarespace Code Block.
#
# Run from anywhere:  ./website/legal/build.sh
#
set -euo pipefail
cd "$(dirname "$0")"

title_for() {
  case "$1" in
    privacy-policy)          echo "Privacy Policy — Soulfull Gatherings" ;;
    terms-of-service)        echo "Terms of Service — Soulfull Gatherings" ;;
    retreat-booking-policy)  echo "Retreat Booking & Cancellation Policy — Soulfull Gatherings" ;;
  esac
}

for src in src/*.body.html; do
  slug="$(basename "$src" .body.html)"
  out="${slug}.html"

  {
    printf '%s\n' '<!DOCTYPE html>'
    printf '%s\n' '<html lang="en">'
    printf '%s\n' '<head>'
    printf '%s\n' '<meta charset="utf-8">'
    printf '%s\n' '<meta name="viewport" content="width=device-width, initial-scale=1">'
    printf '<title>%s</title>\n' "$(title_for "$slug")"
    printf '%s\n' '<meta name="robots" content="index, follow">'
    printf '%s\n' '<!-- Generated by build.sh from _shared.css + src/'"$slug"'.body.html. Edit those, not this. -->'
    printf '%s\n' '<style>'
    cat _shared.css
    printf '%s\n' '</style>'
    printf '%s\n' '</head>'
    printf '%s\n' '<body>'
    printf '%s\n' '<div class="sg-legal">'
    cat "$src"
    printf '%s\n' '</div>'
    printf '%s\n' '</body>'
    printf '%s\n' '</html>'
  } > "$out"

  echo "  built $out  ($(wc -c < "$out" | tr -d ' ') bytes)"
done

echo
# `grep -c` exits 1 when a file has no matches, which under `set -e` would fail
# the build on the one outcome we actually want. `|| true` keeps that honest.
echo "Unfilled placeholders remaining (0 is what you want before publishing):"
grep -c 'class="todo"' ./*.html 2>/dev/null | sed 's/^/  /' || true
